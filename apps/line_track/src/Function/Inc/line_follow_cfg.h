/**
 * @file line_follow_cfg.h
 * @brief 四路红外巡线参数 · 四轮增量式 PI（编码器闭环）
 *
 * 传感器几何（左→右 p1..p4）：
 *   p1-p2 = 32.9mm  p2-p3 = 14.5mm  p3-p4 = 32.9mm
 *   线宽 ~18mm，白底黑线
 */
#ifndef LINE_FOLLOW_CFG_H
#define LINE_FOLLOW_CFG_H

/* ================================================================
 * 速度档位 — 编码器脉冲/控制周期（10ms）
 * ================================================================ */
#define SPD_GEAR_0                     (0)
#define SPD_GEAR_1                     (5)
#define SPD_GEAR_2                     (15)
#define SPD_GEAR_3                     (20)
#define SPD_GEAR_COUNT                 (4)

/* ================================================================
 * 传感器权重（左负右正，取自参考工程）
 *   外侧权重大（±8）、内侧小（±0.5），偏离时外侧主导
 * ================================================================ */
#define LF_W0                          (-2.5f)
#define LF_W1                          (-0.4f)
#define LF_W2                          (+0.4f)
#define LF_W3                          (+2.5f)

/* ================================================================
 * 丢线外推（线在 p1-p2 / p3-p4 间隙，四路全 0 时）
 *   传感器非等距：p2-p3=14.5mm（密），p1-p2=p3-p4=32.9mm（疏），线宽~18mm。
 *   线落入外侧 32.9mm 间隙时四路全 0；若只保持上次误差（内侧 ±0.4），
 *   修正太弱，车在弯道“一顿一顿”，等 p1/p4 触发才猛打方向。
 *   丢线时按 LF_LOST_STEP 每周期向最后所见方向递增 error，直至外侧权重
 *   (LF_W0/LF_W3)，使 p1/p4 触发时误差已近满幅 → 平滑衔接、提前修正。
 *   ↑STEP：间隙内修正建立更快（过冲风险）；↓STEP：更平缓。
 * ================================================================ */
#define LF_LOST_STEP                   (5.0f)

/* ================================================================
 * 位置 PID（线偏移 → 速度修正），位置式，积分限幅
 *   pid = LF_KP*error + LF_KI*integral + LF_KD*(error-last_error)
 *   增益取自参考工程，需上机精调
 * ================================================================ */
#define LF_KP                          (5.0f)
#define LF_KI                          (0.03f)
#define LF_KD                          (1.2f)
#define LF_I_MAX                       (15.0f)

/* ================================================================
 * 差速限幅（相对 base speed 的比例，有符号 → 允许内轮反转）
 *   left/right = base ∓ pid，pid 限幅 = base*LF_PID_OUT_FRAC
 *   左右轮速度限幅 = base*LF_MAX_SPD_FRAC
 * ================================================================ */
#define LF_PID_OUT_FRAC                (1.2f)
#define LF_MAX_SPD_FRAC                (1.25f)

/* ================================================================
 * 四轮速度环 —— 增量式 PI（移植自参考工程 Velocity_A/B）
 *
 *   u(k) = u(k-1) + SPD_KP*bias + SPD_KI*(bias - last_bias)
 *   bias = 目标速度 - 编码器增量 (pulses / 10ms)
 *   输入单位：encoder pulses / 10ms
 *   输出单位：PWM duty（直接送给 Motor_Set，含符号）
 *
 *   SPD_KP  作用于 bias      —— 累计成 PWM（积分作用）
 *   SPD_KI  作用于 Δbias     —— 限制加速度/抑制震荡
 *   输出 u 即 PWM duty，限幅 ±SPD_OUT_MAX（对齐 motor_cfg.h PWM_MAX）
 *
 * 注：增益取自参考工程（两轮/PWM周期8000/限幅±6000）；本工程为四轮/PWM周期4000/
 *     限幅±3800/编码器PPR不同，上电后必须重新精调 SPD_KP / SPD_KI。
 * ================================================================ */
#define SPD_KP                         (30.0f)    /* 增量式PI：偏差积分项 */
#define SPD_KI                         (2.0f)     /* 增量式PI：偏差变化项（加速度限制） */
#define SPD_OUT_MAX                    (3800.0f)  /* 输出限幅 (PWM)，对齐 motor_cfg.h PWM_MAX */

#endif /* LINE_FOLLOW_CFG_H */